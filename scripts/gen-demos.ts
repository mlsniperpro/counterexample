/**
 * Generates src/lib/problems/demos.generated.ts from bench/solutions so the
 * UI's built-in buggy demos and the benchmark never drift apart.
 * Run with: pnpm gen:demos
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const DEMO_FILES: Record<string, string> = {
  "binary-search": "bug-a.py",
  isqrt: "bug-a.js",
  "coin-change": "bug-a.py",
  "shortest-paths": "bug-a.py",
  "longest-unique-substring": "bug-a.js",
};

/** Split the "# BUG: ..." / "// CORRECT: ..." header line from a solution file. */
export function splitHeader(src: string): { kind: "bug" | "correct"; bug: string; code: string } {
  const [first = "", ...rest] = src.split("\n");
  const m = /^(?:#|\/\/)\s*(BUG|CORRECT):\s*(.*)$/.exec(first);
  if (!m) throw new Error(`missing BUG/CORRECT header: ${first}`);
  return { kind: m[1] === "BUG" ? "bug" : "correct", bug: m[2] ?? "", code: rest.join("\n") };
}

export function renderDemos(root: string): string {
  const entries = Object.entries(DEMO_FILES).map(([id, file]) => {
    const src = readFileSync(join(root, "bench/solutions", id, file), "utf8");
    const { bug, code } = splitHeader(src);
    return `  ${JSON.stringify(id)}: { code: ${JSON.stringify(code)}, bug: ${JSON.stringify(bug)} },`;
  });
  const refs = readdirSync(join(root, "bench/solutions"))
    .sort()
    .map((id) => {
      const file = readdirSync(join(root, "bench/solutions", id)).find((f) => f.startsWith("correct."));
      if (!file) throw new Error(`bench/solutions/${id} has no correct solution`);
      const { code } = splitHeader(readFileSync(join(root, "bench/solutions", id, file), "utf8"));
      return `  ${JSON.stringify(id)}: ${JSON.stringify(code)},`;
    });
  return (
    `// Generated by scripts/gen-demos.ts from bench/solutions. Do not edit.\n` +
    `export const DEMOS: Record<string, { code: string; bug: string }> = {\n${entries.join("\n")}\n};\n\n` +
    `/** Correct reference solutions, used as the replayed "fix" when a demo's code has been edited. */\n` +
    `export const REFERENCES: Record<string, string> = {\n${refs.join("\n")}\n};\n`
  );
}

if (process.argv[1]?.endsWith("gen-demos.ts")) {
  const root = process.cwd();
  writeFileSync(join(root, "src/lib/problems/demos.generated.ts"), renderDemos(root));
  console.log("wrote src/lib/problems/demos.generated.ts");
}
